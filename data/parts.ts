export function styleLabel(style: PartStyle) {
  return style === "factory" ? "Factory" : "Tubular";
}

export function partsForYear(
  year: MustangYear,
  area: SuspensionAreaId,
  armStyle: ArmStyleId = "all",
) {
  return PARTS.filter((part) => {
    if (part.area !== area) return false;
    if (!part.years.includes(year)) return false;
    if (armStyle !== "all" && part.style !== armStyle) return false;
    return true;
  });
}

export function partBySlug(slug: string) {
  return PARTS.find((part) => part.slug === slug);
}
